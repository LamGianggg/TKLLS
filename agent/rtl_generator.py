"""
Module: rtl_generator.py
Description: Automated Verilog RTL Code Generator for Spec2RTL & Prompt2Silicon.
Parses hardware specifications and synthesizes clean, synthesizable IEEE 1364-2001 Verilog.
"""

import os

class RTLGenerator:
    def __init__(self, src_dir):
        self.src_dir = src_dir
        os.makedirs(src_dir, exist_ok=True)

    def generate_vending_machine(self, spec_text=""):
        """Generates synthesizable Verilog for Vending Machine from spec."""
        code = """//==============================================================================
// Module: vending_machine
// Description: Automatic Beverage Vending Machine FSM
// Auto-generated by Spec2RTL Engine
//==============================================================================
module vending_machine (
    input  wire       clk,
    input  wire       clr,
    input  wire       coin_5k,    // 5.000 VND inserted
    input  wire       coin_10k,   // 10.000 VND inserted
    output reg        dispense,   // 1: Dispense beverage
    output reg        change_5k,  // 1: Return 5.000 VND change
    output reg  [4:0] balance,    // Current balance in thousands (0, 5, 10, 15, 20)
    output wire [2:0] state_out
);

    localparam S_0K        = 3'b000;
    localparam S_5K        = 3'b001;
    localparam S_10K       = 3'b010;
    localparam S_DISPENSE  = 3'b011; // 15k: Dispense
    localparam S_CHANGE    = 3'b100; // 20k: Dispense + 5k change

    reg [2:0] state, next_state;

    assign state_out = state;

    always @(posedge clk or posedge clr) begin
        if (clr)
            state <= S_0K;
        else
            state <= next_state;
    end

    always @(*) begin
        next_state = state;
        case (state)
            S_0K: begin
                if (coin_10k)
                    next_state = S_10K;
                else if (coin_5k)
                    next_state = S_5K;
            end

            S_5K: begin
                if (coin_10k)
                    next_state = S_DISPENSE;
                else if (coin_5k)
                    next_state = S_10K;
            end

            S_10K: begin
                if (coin_10k)
                    next_state = S_CHANGE;
                else if (coin_5k)
                    next_state = S_DISPENSE;
            end

            S_DISPENSE: begin
                next_state = S_0K;
            end

            S_CHANGE: begin
                next_state = S_0K;
            end

            default: next_state = S_0K;
        endcase
    end

    always @(*) begin
        dispense  = 1'b0;
        change_5k = 1'b0;
        balance   = 5'd0;

        case (state)
            S_0K:        balance = 5'd0;
            S_5K:        balance = 5'd5;
            S_10K:       balance = 5'd10;
            S_DISPENSE: begin
                balance  = 5'd15;
                dispense = 1'b1;
            end
            S_CHANGE: begin
                balance   = 5'd20;
                dispense  = 1'b1;
                change_5k = 1'b1;
            end
            default: balance = 5'd0;
        endcase
    end

endmodule
"""
        out_path = os.path.join(self.src_dir, "vending_machine.v")
        with open(out_path, "w", encoding="utf-8") as f:
            f.write(code)
        return out_path

    def generate_traffic_light(self, spec_text=""):
        """Generates synthesizable Verilog for Traffic Light from spec."""
        code = """//==============================================================================
// Module: traffic_light
// Description: Intersection Traffic Light Controller (Generated via Spec2RTL)
// Controls Main Street and Side Street lights using a timed FSM
//==============================================================================
module traffic_light (
    input  wire       clk,
    input  wire       clr,
    input  wire       car_sensor,
    output reg  [2:0] light_main,  // {Red, Yellow, Green}
    output reg  [2:0] light_side,  // {Red, Yellow, Green}
    output wire [1:0] state_out
);

    localparam COLOR_GREEN  = 3'b001;
    localparam COLOR_YELLOW = 3'b010;
    localparam COLOR_RED    = 3'b100;

    localparam S0_MAIN_GREEN  = 2'b00;
    localparam S1_MAIN_YELLOW = 2'b01;
    localparam S2_SIDE_GREEN  = 2'b10;
    localparam S3_SIDE_YELLOW = 2'b11;

    localparam TIME_GREEN  = 4'd10;
    localparam TIME_YELLOW = 4'd3;

    reg [1:0] state, next_state;
    reg [3:0] timer;

    assign state_out = state;

    always @(posedge clk or posedge clr) begin
        if (clr) begin
            state <= S0_MAIN_GREEN;
            timer <= 4'd0;
        end else begin
            if (state != next_state) begin
                state <= next_state;
                timer <= 4'd0;
            end else begin
                timer <= timer + 1'b1;
            end
        end
    end

    always @(*) begin
        next_state = state;
        case (state)
            S0_MAIN_GREEN: begin
                if ((timer >= (TIME_GREEN - 1'b1)) && car_sensor)
                    next_state = S1_MAIN_YELLOW;
            end

            S1_MAIN_YELLOW: begin
                if (timer >= (TIME_YELLOW - 1'b1))
                    next_state = S2_SIDE_GREEN;
            end

            S2_SIDE_GREEN: begin
                if (timer >= (TIME_GREEN - 1'b1))
                    next_state = S3_SIDE_YELLOW;
            end

            S3_SIDE_YELLOW: begin
                if (timer >= (TIME_YELLOW - 1'b1))
                    next_state = S0_MAIN_GREEN;
            end

            default: next_state = S0_MAIN_GREEN;
        endcase
    end

    always @(*) begin
        case (state)
            S0_MAIN_GREEN: begin
                light_main = COLOR_GREEN;
                light_side = COLOR_RED;
            end

            S1_MAIN_YELLOW: begin
                light_main = COLOR_YELLOW;
                light_side = COLOR_RED;
            end

            S2_SIDE_GREEN: begin
                light_main = COLOR_RED;
                light_side = COLOR_GREEN;
            end

            S3_SIDE_YELLOW: begin
                light_main = COLOR_RED;
                light_side = COLOR_YELLOW;
            end

            default: begin
                light_main = COLOR_GREEN;
                light_side = COLOR_RED;
            end
        endcase
    end

endmodule
"""
        out_path = os.path.join(self.src_dir, "traffic_light.v")
        with open(out_path, "w", encoding="utf-8") as f:
            f.write(code)
        return out_path

    def generate_elevator_controller(self, spec_text=""):
        """Generates synthesizable Verilog for 5-Floor Elevator Controller."""
        code = """//==============================================================================
// Module: elevator_controller
// Description: 5-Floor Intelligent Elevator Controller FSM
// Auto-generated by Spec2RTL Engine
//==============================================================================
module elevator_controller (
    input  wire       clk,
    input  wire       clr,
    input  wire [4:0] floor_req,     // Buttons for floors 1..5 (bit 0 = floor 1, bit 4 = floor 5)
    output reg  [2:0] current_floor, // 1 to 5
    output reg        door_open,     // 1: Door is open, 0: Door is closed
    output reg        motor_up,      // 1: Motor moving up
    output reg        motor_down,    // 1: Motor moving down
    output wire [1:0] state_out
);

    localparam S_IDLE      = 2'b00;
    localparam S_UP        = 2'b01;
    localparam S_DOWN      = 2'b10;
    localparam S_DOOR_OPEN = 2'b11;

    reg [1:0] state;
    reg [4:0] requests;
    reg [1:0] door_cnt;

    assign state_out = state;

    wire [4:0] all_req;
    assign all_req = requests | floor_req;

    always @(posedge clk or posedge clr) begin
        if (clr) begin
            state         <= S_IDLE;
            current_floor <= 3'd1;
            requests      <= 5'd0;
            door_cnt      <= 2'd0;
            door_open     <= 1'b0;
            motor_up      <= 1'b0;
            motor_down    <= 1'b0;
        end else begin
            requests <= requests | floor_req;

            case (state)
                S_IDLE: begin
                    motor_up   <= 1'b0;
                    motor_down <= 1'b0;
                    door_open  <= 1'b0;
                    door_cnt   <= 2'd0;

                    if (all_req != 5'd0) begin
                        if (all_req[current_floor - 1'b1]) begin
                            state     <= S_DOOR_OPEN;
                            door_open <= 1'b1;
                        end else if (all_req > (5'b00001 << (current_floor - 1'b1))) begin
                            state    <= S_UP;
                            motor_up <= 1'b1;
                        end else begin
                            state      <= S_DOWN;
                            motor_down <= 1'b1;
                        end
                    end
                end

                S_UP: begin
                    motor_up <= 1'b1;
                    if (current_floor < 3'd5)
                        current_floor <= current_floor + 1'b1;

                    if (all_req[current_floor]) begin
                        state     <= S_DOOR_OPEN;
                        motor_up  <= 1'b0;
                        door_open <= 1'b1;
                    end
                end

                S_DOWN: begin
                    motor_down <= 1'b1;
                    if (current_floor > 3'd1)
                        current_floor <= current_floor - 1'b1;

                    if (all_req[current_floor - 2'd2]) begin
                        state      <= S_DOOR_OPEN;
                        motor_down <= 1'b0;
                        door_open  <= 1'b1;
                    end
                end

                S_DOOR_OPEN: begin
                    motor_up   <= 1'b0;
                    motor_down <= 1'b0;
                    door_open  <= 1'b1;
                    requests[current_floor - 1'b1] <= 1'b0;

                    if (door_cnt >= 2'd2) begin
                        door_open <= 1'b0;
                        door_cnt  <= 2'd0;
                        state     <= S_IDLE;
                    end else begin
                        door_cnt <= door_cnt + 1'b1;
                    end
                end
            endcase
        end
    end

endmodule
"""
        out_path = os.path.join(self.src_dir, "elevator_controller.v")
        with open(out_path, "w", encoding="utf-8") as f:
            f.write(code)
        return out_path
