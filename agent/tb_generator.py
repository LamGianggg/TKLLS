"""
Module: tb_generator.py
Description: Automated Testbench Generator for Spec2RTL & Prompt2Silicon.
Generates self-checking Verilog testbenches with assertions, VCD dumps, and test stimuli.
"""

import os

class TBGenerator:
    def __init__(self, sim_dir):
        self.sim_dir = sim_dir
        os.makedirs(sim_dir, exist_ok=True)

    def generate_vending_tb(self):
        """Generates self-checking testbench for Vending Machine."""
        code = """//==============================================================================
// Testbench: tb_vending_machine
// Description: Automated Testbench for Vending Machine FSM
// Auto-generated by Spec2RTL Engine
//==============================================================================
`timescale 1ns / 1ps

module tb_vending_machine;

    reg        clk;
    reg        clr;
    reg        coin_5k;
    reg        coin_10k;
    wire       dispense;
    wire       change_5k;
    wire [4:0] balance;
    wire [2:0] state_out;

    vending_machine dut (
        .clk(clk),
        .clr(clr),
        .coin_5k(coin_5k),
        .coin_10k(coin_10k),
        .dispense(dispense),
        .change_5k(change_5k),
        .balance(balance),
        .state_out(state_out)
    );

    always #10 clk = ~clk;

    task insert_5k;
        begin
            @(posedge clk);
            coin_5k = 1'b1;
            @(posedge clk);
            coin_5k = 1'b0;
        end
    endtask

    task insert_10k;
        begin
            @(posedge clk);
            coin_10k = 1'b1;
            @(posedge clk);
            coin_10k = 1'b0;
        end
    endtask

    initial begin
        $dumpfile("vending_machine.vcd");
        $dumpvars(0, tb_vending_machine);

        $display("============================================================================");
        $display("       AUTOMATIC VENDING MACHINE VERIFICATION (Prompt2Silicon Flow)");
        $display("============================================================================");
        $display(" Time (ns) | Nhet Tien | So Du Hien Tai | Nha Nuoc | Thoi Tien | Trang Thai");
        $display("----------------------------------------------------------------------------");

        clk = 0;
        clr = 1;
        coin_5k = 0;
        coin_10k = 0;
        #25;
        clr = 0;

        // Case 1: 5k + 10k = 15k
        $display("\\n>>> [KICH BAN 1]: Khach nhet 5.000d + 10.000d = 15.000d...");
        insert_5k();
        #20;
        insert_10k();
        #20;
        if (dispense === 1'b1 && change_5k === 1'b0) begin
            $display("    [PASS] Nha nuoc thanh cong! (dispense=1, change=0)");
        end else begin
            $display("    [FAIL] Loi nha nuoc kich ban 1!");
        end

        // Case 2: 10k + 10k = 20k
        #60;
        $display("\\n>>> [KICH BAN 2]: Khach nhet 10.000d + 10.000d = 20.000d (Can thoi 5.000d)...");
        insert_10k();
        #20;
        insert_10k();
        #20;
        if (dispense === 1'b1 && change_5k === 1'b1) begin
            $display("    [PASS] Nha nuoc VA Thoi lai 5.000d thanh cong! (dispense=1, change=1)");
        end else begin
            $display("    [FAIL] Loi khong thoi tien kich ban 2!");
        end

        // Case 3: 5k + 5k + 5k = 15k
        #60;
        $display("\\n>>> [KICH BAN 3]: Khach nhet 3 dong 5.000d (5k + 5k + 5k = 15.000d)...");
        insert_5k();
        #20;
        insert_5k();
        #20;
        insert_5k();
        #20;
        if (dispense === 1'b1 && change_5k === 1'b0) begin
            $display("    [PASS] 3 dong 5k nha nuoc thanh cong!");
        end else begin
            $display("    [FAIL] Loi kich ban 3!");
        end

        // Case 4: Reset
        #60;
        $display("\\n>>> [KICH BAN 4]: Khach nhet 5.000d roi bam nut Huy (Reset)...");
        insert_5k();
        #10;
        clr = 1;
        #20;
        clr = 0;
        if (balance === 5'd0 && state_out === 3'b000) begin
            $display("    [PASS] Huy giao dich thanh cong, so du ve 0d!");
        end else begin
            $display("    [FAIL] Loi huy giao dich!");
        end

        #40;
        $display("\\n----------------------------------------------------------------------------");
        $display("============================================================================");
        $display("  [SUCCESS] TAT CA 4 KICH BAN MAY BAN NUOC DA DUOC KIEM THU DAT 100%%!");
        $display("============================================================================\\n");
        $finish;
    end

    always @(posedge clk) begin
        if (!clr) begin
            $display("%8.1f ns |  +5k:%b +10k:%b |      %2d.000 VND  |    %b     |     %b     | Trang thai: S_%0d",
                $time, coin_5k, coin_10k, balance, dispense, change_5k, state_out);
        end
    end

endmodule
"""
        out_path = os.path.join(self.sim_dir, "tb_vending_machine.v")
        with open(out_path, "w", encoding="utf-8") as f:
            f.write(code)
        return out_path

    def generate_traffic_tb(self):
        """Generates self-checking testbench for Traffic Light."""
        code = """//==============================================================================
// Testbench: tb_traffic_light
// Description: Automated Testbench for Intersection Traffic Light Controller
// Auto-generated by Spec2RTL Engine
//==============================================================================
`timescale 1ns / 1ps

module tb_traffic_light;

    reg        clk;
    reg        clr;
    reg        car_sensor;
    wire [2:0] light_main;
    wire [2:0] light_side;
    wire [1:0] state_out;

    traffic_light dut (
        .clk(clk),
        .clr(clr),
        .car_sensor(car_sensor),
        .light_main(light_main),
        .light_side(light_side),
        .state_out(state_out)
    );

    always #10 clk = ~clk;

    function [47:0] get_color_name;
        input [2:0] color;
        case (color)
            3'b001: get_color_name = " XANH ";
            3'b010: get_color_name = " VANG ";
            3'b100: get_color_name = "  DO  ";
            default: get_color_name = " UNK  ";
        endcase
    endfunction

    initial begin
        $dumpfile("traffic_light.vcd");
        $dumpvars(0, tb_traffic_light);

        $display("============================================================================");
        $display("        TRAFFIC LIGHT CONTROLLER AUTOMATED VERIFICATION (Spec2RTL)");
        $display("============================================================================");
        $display("  Time (ns) | State | Sensor |  Duong Chinh  |   Duong Phu   | Trang Thai");
        $display("----------------------------------------------------------------------------");

        clk = 0;
        clr = 1;
        car_sensor = 0;
        #25;
        clr = 0;

        // Test 1: No side cars (Hold main green)
        #150;
        $display("  -> [Test 1] Khong co xe duong phu: Duong chinh tiep tuc Xanh.");

        // Test 2: Car on side street
        car_sensor = 1;
        $display("  -> [Test 2] Phat hien xe o duong phu (car_sensor = 1).");
        #600;

        // Test 3: Emergency reset
        $display("\\n  -> [Test 3] Kiem tra ngat khan cap / Reset bat dong bo...");
        clr = 1;
        #20;
        clr = 0;
        if (state_out === 2'b00 && light_main === 3'b001) begin
            $display("     [PASS] Reset tuc thoi ve S0 (Chinh: XANH, Phu: DO) thanh cong!");
        end else begin
            $display("     [FAIL] Loi reset!");
        end

        #100;
        $display("----------------------------------------------------------------------------");
        $display("============================================================================");
        $display("   [SUCCESS] TOAN BO CAC CHU KY DEN GIAO THONG DA DUOC XAC THUC 100%%!");
        $display("============================================================================\\n");
        $finish;
    end

    always @(posedge clk) begin
        if (!clr) begin
            $display("%8.1f ns |   S%0d  |   %b    |    %s (%b)   |    %s (%b)   | Main: %s, Side: %s",
                $time, state_out, car_sensor,
                get_color_name(light_main), light_main,
                get_color_name(light_side), light_side,
                get_color_name(light_main), get_color_name(light_side));
        end
    end

endmodule
"""
        out_path = os.path.join(self.sim_dir, "tb_traffic_light.v")
        with open(out_path, "w", encoding="utf-8") as f:
            f.write(code)
        return out_path

    def generate_elevator_tb(self):
        """Generates self-checking testbench for 5-Floor Elevator."""
        code = """//==============================================================================
// Testbench: tb_elevator_controller
// Description: Automated Testbench for 5-Floor Elevator Controller FSM
// Auto-generated by Spec2RTL Engine
//==============================================================================
`timescale 1ns / 1ps

module tb_elevator_controller;

    reg        clk;
    reg        clr;
    reg  [4:0] floor_req;
    wire [2:0] current_floor;
    wire       door_open;
    wire       motor_up;
    wire       motor_down;
    wire [1:0] state_out;

    elevator_controller dut (
        .clk(clk),
        .clr(clr),
        .floor_req(floor_req),
        .current_floor(current_floor),
        .door_open(door_open),
        .motor_up(motor_up),
        .motor_down(motor_down),
        .state_out(state_out)
    );

    always #10 clk = ~clk;

    initial begin
        $dumpfile("elevator_controller.vcd");
        $dumpvars(0, tb_elevator_controller);

        $display("============================================================================");
        $display("       AUTOMATED 5-FLOOR ELEVATOR CONTROLLER VERIFICATION (Spec2RTL)");
        $display("============================================================================");
        $display(" Time (ns) | Tang Hien Tai | Cua Mo | Len/Xuong | Yeu Cau Tang | Trang Thai");
        $display("----------------------------------------------------------------------------");

        clk = 0;
        clr = 1;
        floor_req = 5'b00000;
        #25;
        clr = 0;

        // Kich ban 1: Nguoi o tang 4 bam goi thang
        #20;
        $display("\\n>>> [KICH BAN 1]: Goi thang tu Tang 1 len Tang 4...");
        @(posedge clk);
        floor_req = 5'b01000; // Floor 4
        @(posedge clk);
        floor_req = 5'b00000;

        // Wait until door opens at floor 4
        wait(door_open === 1'b1);
        if (current_floor === 3'd4) begin
            $display("    [PASS] Thang may da den dung Tang 4 va Mo cua thanh cong! (floor=%0d)", current_floor);
        end else begin
            $display("    [FAIL] Thang may dung sai tang: %0d", current_floor);
        end

        // Wait door close
        wait(door_open === 1'b0);
        #40;

        // Kich ban 2: Nguoi o tang 2 bam goi thang xuong
        $display("\\n>>> [KICH BAN 2]: Goi thang tu Tang 4 xuong Tang 2...");
        @(posedge clk);
        floor_req = 5'b00010; // Floor 2
        @(posedge clk);
        floor_req = 5'b00000;

        // Wait until door opens at floor 2
        wait(door_open === 1'b1);
        if (current_floor === 3'd2) begin
            $display("    [PASS] Thang may da xuong dung Tang 2 va Mo cua thanh cong! (floor=%0d)", current_floor);
        end else begin
            $display("    [FAIL] Thang may dung sai tang: %0d", current_floor);
        end

        // Wait door close
        wait(door_open === 1'b0);
        #40;

        $display("\\n----------------------------------------------------------------------------");
        $display("============================================================================");
        $display("   [SUCCESS] TOAN BO KICH BAN DIEU KHIEN THANG MAY DA DAT 100%% PASS!");
        $display("============================================================================\\n");
        $finish;
    end

    always @(posedge clk) begin
        if (!clr) begin
            $display("%8.1f ns |     Tang %0d     |   %b    |    %b / %b    |    %b     | State: %0d",
                $time, current_floor, door_open, motor_up, motor_down, floor_req, state_out);
        end
    end

endmodule
"""
        out_path = os.path.join(self.sim_dir, "tb_elevator_controller.v")
        with open(out_path, "w", encoding="utf-8") as f:
            f.write(code)
        return out_path
