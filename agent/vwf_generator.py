"""
Module: vwf_generator.py
Description: Generates standard Altera / Intel Quartus II 13.0sp1 Vector Waveform Files (.vwf).
Enables users to open, view, and run functional simulations directly inside Quartus II Waveform Editor.
"""

import os
import re

class VWFGenerator:
    def __init__(self):
        pass

    def generate_vwf_from_rtl(self, rtl_path, vwf_path, duration_ns=1000.0):
        """Extracts ports from a synthesizable Verilog module and creates a valid Quartus II .vwf file."""
        if not os.path.exists(rtl_path):
            return None

        with open(rtl_path, "r", encoding="utf-8", errors="replace") as f:
            code = f.read()

        # Strip comments
        c = re.sub(r"//.*", "", code)
        c = re.sub(r"/\*.*?\*/", "", c, flags=re.DOTALL)

        m_mod = re.search(r"module\s+([A-Za-z0-9_]+)\s*(?:#\s*\(.*?\)\s*)?\((.*?)\);", c, re.DOTALL)
        if not m_mod:
            return None

        mod_name = m_mod.group(1)
        port_block = m_mod.group(2)

        ports = []
        for line in port_block.split(","):
            line = line.strip()
            m_p = re.search(r"(input|output|inout)\s+(?:wire|reg)?\s*(?:\[(\d+):(\d+)\])?\s*([A-Za-z0-9_]+)", line)
            if m_p:
                direction, msb, lsb, name = m_p.groups()
                w = (int(msb) - int(lsb) + 1) if msb and lsb else 1
                ports.append({
                    "name": name,
                    "direction": direction.upper(),
                    "width": w,
                    "msb": int(msb) if msb else 0,
                    "lsb": int(lsb) if lsb else 0,
                    "is_bus": w > 1
                })

        header = f"""/* Simulator = Quartus II Simulator */
/* Auto-generated by Spec2RTL & Prompt2Silicon Framework */
HEADER
{{
\tVERSION = 1;
\tTIME_UNIT = ns;
\tDATA_OFFSET = 0.0;
\tDATA_DURATION = {duration_ns:.1f};
\tSIMULATION_TIME = 0.0;
\tGRID_PHASE = 0.0;
\tGRID_PERIOD = 10.0;
\tGRID_DUTY_CYCLE = 50;
}}
"""

        signal_blocks = []
        transition_blocks = []
        display_lines = []

        clock_names = ["clk", "clock", "sys_clk"]
        reset_names = ["rst_n", "rst", "reset", "clr", "clear"]

        for p in ports:
            p_name = p["name"]
            p_dir = p["direction"]
            w = p["width"]

            if not p["is_bus"]:
                # Single-bit signal
                signal_blocks.append(f"""SIGNAL("{p_name}")
{{
\tVALUE_TYPE = NINE_LEVEL_BIT;
\tSIGNAL_TYPE = SINGLE_BIT;
\tWIDTH = 1;
\tLSB_INDEX = -1;
\tDIRECTION = {p_dir};
\tPARENT = "";
}}""")
                display_lines.append(f"""DISPLAY_LINE
{{
\tCHANNEL = "{p_name}";
\tEXPAND_STATUS = COLLAPSED;
\tRADIX = Binary;
\tTREE_INDEX = {len(display_lines)};
\tTREE_LEVEL = 0;
}}""")

                # Transition logic
                if p_name.lower() in clock_names:
                    # Periodic Clock
                    cycles = int(duration_ns // 10)
                    transition_blocks.append(f"""TRANSITION_LIST("{p_name}")
{{
\tNODE
\t{{
\t\tREPEAT = 1;
\t\tNODE
\t\t{{
\t\t\tREPEAT = {cycles};
\t\t\tLEVEL 0 FOR 5.0;
\t\t\tLEVEL 1 FOR 5.0;
\t\t}}
\t}}
}}""")
                elif p_name.lower() in reset_names:
                    # Reset pulse
                    is_active_low = "n" in p_name.lower()
                    init_level = 0 if is_active_low else 1
                    rest_level = 1 if is_active_low else 0
                    transition_blocks.append(f"""TRANSITION_LIST("{p_name}")
{{
\tNODE
\t{{
\t\tREPEAT = 1;
\t\tLEVEL {init_level} FOR 20.0;
\t\tLEVEL {rest_level} FOR {duration_ns - 20.0:.1f};
\t}}
}}""")
                elif p_dir == "INPUT":
                    # Input stimulus pulses
                    transition_blocks.append(f"""TRANSITION_LIST("{p_name}")
{{
\tNODE
\t{{
\t\tREPEAT = 1;
\t\tLEVEL 0 FOR 40.0;
\t\tLEVEL 1 FOR 20.0;
\t\tLEVEL 0 FOR 80.0;
\t\tLEVEL 1 FOR 20.0;
\t\tLEVEL 0 FOR {max(10.0, duration_ns - 160.0):.1f};
\t}}
}}""")
                else:
                    # Output
                    transition_blocks.append(f"""TRANSITION_LIST("{p_name}")
{{
\tNODE
\t{{
\t\tREPEAT = 1;
\t\tLEVEL X FOR {duration_ns:.1f};
\t}}
}}""")

            else:
                # Bus Signal (e.g. balance[4..0])
                bus_name = p_name
                signal_blocks.append(f"""SIGNAL("{bus_name}")
{{
\tVALUE_TYPE = NINE_LEVEL_BIT;
\tSIGNAL_TYPE = BUS;
\tWIDTH = {w};
\tLSB_INDEX = 0;
\tDIRECTION = {p_dir};
\tPARENT = "";
}}""")
                display_lines.append(f"""DISPLAY_LINE
{{
\tCHANNEL = "{bus_name}";
\tEXPAND_STATUS = EXPANDED;
\tRADIX = Unsigned;
\tTREE_INDEX = {len(display_lines)};
\tTREE_LEVEL = 0;
\tCHILDREN = {", ".join([f'"{bus_name}[{i}]"' for i in reversed(range(w))])};
}}""")
                # Bus children
                for bit_idx in reversed(range(w)):
                    bit_name = f"{bus_name}[{bit_idx}]"
                    signal_blocks.append(f"""SIGNAL("{bit_name}")
{{
\tVALUE_TYPE = NINE_LEVEL_BIT;
\tSIGNAL_TYPE = SINGLE_BIT;
\tWIDTH = 1;
\tLSB_INDEX = -1;
\tDIRECTION = {p_dir};
\tPARENT = "{bus_name}";
}}""")
                    display_lines.append(f"""DISPLAY_LINE
{{
\tCHANNEL = "{bit_name}";
\tEXPAND_STATUS = COLLAPSED;
\tRADIX = Unsigned;
\tTREE_INDEX = {len(display_lines)};
\tTREE_LEVEL = 1;
\tPARENT = "{bus_name}";
}}""")
                    transition_blocks.append(f"""TRANSITION_LIST("{bit_name}")
{{
\tNODE
\t{{
\t\tREPEAT = 1;
\t\tLEVEL {'0' if p_dir == 'INPUT' else 'X'} FOR {duration_ns:.1f};
\t}}
}}""")

        content = header + "\n" + "\n".join(signal_blocks) + "\n\n" + "\n".join(transition_blocks) + "\n\n" + "\n".join(display_lines) + "\n"

        with open(vwf_path, "w", encoding="utf-8") as f:
            f.write(content)
        return vwf_path

if __name__ == "__main__":
    gen = VWFGenerator()
    base = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
    rtl = os.path.join(base, "src", "vending_machine.v")
    out = os.path.join(base, "quartus", "Waveform.vwf")
    if os.path.exists(rtl):
        gen.generate_vwf_from_rtl(rtl, out)
        print("Generated Quartus Waveform.vwf at:", out)
