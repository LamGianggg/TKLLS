"""
Module: bdf_generator.py
Description: Automated BDF (Block Design File) Generator from BSF Symbol.
Converts any Quartus .bsf symbol into a complete, clean, grid-aligned .bdf schematic.
"""

import os
import re

class BDFGenerator:
    def __init__(self):
        pass

    def generate_bdf_from_bsf(self, bsf_path, bdf_path, sym_x=400, sym_y=200):
        """Reads a .bsf file, places it in a .bdf, adds pins and wires."""
        with open(bsf_path, "r", encoding="utf-8", errors="replace") as f:
            bsf_text = f.read()

        # Parse symbol rect
        m_rect = re.search(r'\(symbol\s*\n\s*\(rect\s+(\d+)\s+(\d+)\s+(\d+)\s+(\d+)\)', bsf_text)
        if not m_rect:
            raise ValueError(f"Invalid BSF file: {bsf_path}")
        
        orig_w = int(m_rect.group(3)) - int(m_rect.group(1))
        orig_h = int(m_rect.group(4)) - int(m_rect.group(2))
        
        # Round sym_x and sym_y to 8px grid
        sym_x = (sym_x // 8) * 8
        sym_y = (sym_y // 8) * 8
        sym_x2 = sym_x + orig_w
        sym_y2 = sym_y + orig_h

        # Extract port definitions
        port_blocks = re.findall(r'(\(port\s*\n\s*\(pt\s+(\d+)\s+(\d+)\)\s*\n\s*\((input|output)\)\s*\n\s*\(text\s+"([^"]+)".*?\n\t\))', bsf_text, re.DOTALL)

        # Build symbol block for BDF
        # Extract everything inside (symbol ... ) in BSF
        inner_symbol = bsf_text[bsf_text.find('(symbol'):]
        # Replace the rect
        inner_symbol = re.sub(r'\(rect\s+\d+\s+\d+\s+\d+\s+\d+\)', f'(rect {sym_x} {sym_y} {sym_x2} {sym_y2})', inner_symbol, count=1)

        bdf_lines = [
            '/* Auto-generated by Spec2RTL & Prompt2Silicon */',
            '(header "graphic" (version "1.4"))',
            inner_symbol.strip()
        ]

        # Pins and Connectors
        in_pin_x = sym_x - 200
        out_pin_x = sym_x2 + 48

        for full_block, pt_x, pt_y, direction, port_name in port_blocks:
            px = int(pt_x)
            py = int(pt_y)
            abs_port_y = sym_y + py

            is_bus = '[' in port_name and '..' in port_name

            if direction == "input":
                # Input Pin at (in_pin_x, abs_port_y - 8)
                pin_y = abs_port_y - 8
                pin_code = f"""(pin
\t(input)
\t(rect {in_pin_x} {pin_y} {in_pin_x + 168} {pin_y + 16})
\t(text "INPUT" (rect 125 0 153 10)(font "Arial" (font_size 6)))
\t(text "{port_name}" (rect 5 0 {5 + len(port_name)*7} 12)(font "Arial" ))
\t(pt 168 8)
\t(drawing
\t\t(line (pt 84 12)(pt 109 12))
\t\t(line (pt 84 4)(pt 109 4))
\t\t(line (pt 113 8)(pt 168 8))
\t\t(line (pt 84 12)(pt 84 4))
\t\t(line (pt 109 4)(pt 113 8))
\t\t(line (pt 109 12)(pt 113 8))
\t)
\t(text "VCC" (rect 128 7 148 17)(font "Arial" (font_size 6)))
)"""
                bdf_lines.append(pin_code)

                # Connector from pin (in_pin_x + 168, abs_port_y) to symbol (sym_x, abs_port_y)
                line_width = " (line_width 3)" if is_bus else ""
                connector_code = f"""(connector
\t(pt {in_pin_x + 168} {abs_port_y})
\t(pt {sym_x} {abs_port_y}){line_width}
)"""
                bdf_lines.append(connector_code)

            elif direction == "output":
                # Output Pin at (out_pin_x, abs_port_y - 8)
                pin_y = abs_port_y - 8
                pin_code = f"""(pin
\t(output)
\t(rect {out_pin_x} {pin_y} {out_pin_x + 176} {pin_y + 16})
\t(text "OUTPUT" (rect 1 0 39 10)(font "Arial" (font_size 6)))
\t(text "{port_name}" (rect 90 0 {90 + len(port_name)*7} 12)(font "Arial" ))
\t(pt 0 8)
\t(drawing
\t\t(line (pt 0 8)(pt 52 8))
\t\t(line (pt 52 4)(pt 78 4))
\t\t(line (pt 52 12)(pt 78 12))
\t\t(line (pt 52 12)(pt 52 4))
\t\t(line (pt 78 4)(pt 82 8))
\t\t(line (pt 82 8)(pt 78 12))
\t\t(line (pt 78 12)(pt 82 8))
\t)
)"""
                bdf_lines.append(pin_code)

                # Connector from symbol (sym_x2, abs_port_y) to pin (out_pin_x, abs_port_y)
                line_width = " (line_width 3)" if is_bus else ""
                connector_code = f"""(connector
\t(pt {sym_x2} {abs_port_y})
\t(pt {out_pin_x} {abs_port_y}){line_width}
)"""
                bdf_lines.append(connector_code)

        # Write to BDF
        with open(bdf_path, "w", encoding="utf-8") as f:
            f.write('\n'.join(bdf_lines) + '\n')
        return bdf_path

