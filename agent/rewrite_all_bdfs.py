#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Script: rewrite_all_bdfs.py
Description: Rewrites and regenerates ALL Quartus II BSF symbol files,
BDF schematic diagrams, and QSF project configurations for all hardware modules.
Ensures:
  1. Design Verilog (.v) files reside directly in quartus/ alongside .bdf files.
  2. BSF symbols are officially generated by Quartus II (quartus_map --generate_symbol).
  3. BDF schematics are rebuilt with 100% compliant Altera syntax, pin boxes, buses, and grid alignment.
  4. QSF files register both local and relative paths to guarantee zero entity lookup failures.
  5. Every BDF compiles cleanly with 0 errors in Quartus II.
"""

import os
import shutil
import subprocess
import glob
import re
import sys

BASE_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
SRC_DIR = os.path.join(BASE_DIR, "src")
Q_DIR = os.path.join(BASE_DIR, "quartus")

sys.path.insert(0, os.path.join(BASE_DIR, "agent"))
from bdf_generator import BDFGenerator
from eda_finder import find_quartus_map

MODULES = [
    "alu_4bit",
    "barrel_shifter_4bit",
    "counter_16bit",
    "digital_lock_fsm",
    "elevator_controller",
    "fifo_syn",
    "gray_counter_4bit",
    "nhan_8_bit",
    "priority_encoder_8to3",
    "pulse_detector",
    "sequence_detector_1011",
    "shift_reg_universal",
    "top_soc",
    "traffic_light",
    "vending_machine"
]

TOP_SOC_SUBMODULES = [
    "ai_core.v", "ai_datapath.v", "ai_fsm.v", "cpu_controller.v",
    "dma_8237.v", "mac_unit.v", "ram_16x4.v", "relu.v", "vector_counter.v"
]

def entity_to_project_name(entity):
    parts = entity.split("_")
    return "".join(p.capitalize() for p in parts)

def main():
    qmap_exe = find_quartus_map()
    if not qmap_exe or not os.path.exists(qmap_exe):
        print(f"[ERROR] quartus_map.exe not found!")
        sys.exit(1)

    print(f"[*] Found quartus_map: {qmap_exe}")
    print(f"[*] Rewriting and validating all {len(MODULES)} BDF schematics in: {Q_DIR}\n")

    bdf_gen = BDFGenerator()
    results = []

    for mod in MODULES:
        print(f"--------------------------------------------------------------------------------")
        print(f"[*] Processing module: {mod}")
        proj_name = entity_to_project_name(mod)
        v_name = f"{mod}.v"
        src_v = os.path.join(SRC_DIR, v_name)
        q_v = os.path.join(Q_DIR, v_name)
        bsf_path = os.path.join(Q_DIR, f"{mod}.bsf")
        bdf_path = os.path.join(Q_DIR, f"sch_{mod}.bdf")
        qpf_path = os.path.join(Q_DIR, f"{proj_name}.qpf")
        qsf_path = os.path.join(Q_DIR, f"{proj_name}.qsf")

        # 1. Sync Verilog file to quartus/
        if os.path.exists(src_v):
            shutil.copy2(src_v, q_v)
            print(f"  -> [OK] Synced {src_v} -> {q_v}")
        else:
            print(f"  -> [WARNING] Source file not found: {src_v}")

        # 2. Setup QPF & QSF
        with open(qpf_path, "w", encoding="utf-8") as f:
            f.write(f'PROJECT_REVISION = "{proj_name}"\n')

        qsf_lines = [
            'set_global_assignment -name FAMILY "Cyclone II"',
            'set_global_assignment -name DEVICE EP2C35F672C6',
            f'set_global_assignment -name TOP_LEVEL_ENTITY sch_{mod}',
            'set_global_assignment -name ORIGINAL_QUARTUS_VERSION "13.0 SP1"',
            'set_global_assignment -name LAST_QUARTUS_VERSION "13.0 SP1"',
            'set_global_assignment -name SEARCH_PATH .',
            'set_global_assignment -name SEARCH_PATH ../src',
            f'set_global_assignment -name BDF_FILE sch_{mod}.bdf',
            f'set_global_assignment -name VERILOG_FILE {v_name}',
            'set_global_assignment -name VECTOR_WAVEFORM_FILE Waveform.vwf'
        ]

        if mod == "top_soc":
            for sub in TOP_SOC_SUBMODULES:
                sub_src = os.path.join(SRC_DIR, sub)
                sub_dst = os.path.join(Q_DIR, sub)
                if os.path.exists(sub_src):
                    shutil.copy2(sub_src, sub_dst)
                qsf_lines.append(f'set_global_assignment -name VERILOG_FILE {sub}')

        with open(qsf_path, "w", encoding="utf-8") as f:
            f.write("\n".join(qsf_lines) + "\n")
        print(f"  -> [OK] Configured project: {proj_name}.qpf & {proj_name}.qsf")

        # 3. Clean temporary database caches to avoid collisions
        for temp_sub in ["db", "incremental_db"]:
            td = os.path.join(Q_DIR, temp_sub)
            if os.path.exists(td):
                try: shutil.rmtree(td, ignore_errors=True)
                except Exception: pass

        # 4. Generate official BSF symbol using Quartus II
        res_bsf = subprocess.run(
            [qmap_exe, proj_name, f"--generate_symbol={v_name}"],
            cwd=Q_DIR,
            capture_output=True,
            text=True
        )
        if res_bsf.returncode == 0 and os.path.exists(bsf_path):
            print(f"  -> [OK] Quartus generated official BSF symbol: {mod}.bsf")
        else:
            # Fallback to AST generator if quartus symbol creation fails
            bdf_gen.generate_bsf_from_rtl(q_v, bsf_path)
            print(f"  -> [FALLBACK] Generated BSF symbol via AST parser: {mod}.bsf")

        # 5. Generate official BDF schematic from BSF
        bdf_gen.generate_bdf_from_bsf(bsf_path, bdf_path)
        print(f"  -> [OK] Generated BDF schematic: sch_{mod}.bdf")

        # 6. Verify full Quartus Synthesis
        for temp_sub in ["db", "incremental_db"]:
            td = os.path.join(Q_DIR, temp_sub)
            if os.path.exists(td):
                try: shutil.rmtree(td, ignore_errors=True)
                except Exception: pass

        res_synth = subprocess.run(
            [qmap_exe, proj_name, "-c", proj_name],
            cwd=Q_DIR,
            capture_output=True,
            text=True
        )
        synth_success = (res_synth.returncode == 0)
        status_tag = "SUCCESS" if synth_success else "FAILED"
        print(f"  -> [SYNTHESIS]: {status_tag}")
        results.append((mod, synth_success))

    # Also sync top_vending_machine.bdf if needed
    top_vend = os.path.join(Q_DIR, "top_vending_machine.bdf")
    sch_vend = os.path.join(Q_DIR, "sch_vending_machine.bdf")
    if os.path.exists(sch_vend):
        shutil.copy2(sch_vend, top_vend)

    print("\n" + "=" * 80)
    print("                      ALL BDF REWRITE SUMMARY")
    print("=" * 80)
    all_ok = True
    for mod, ok in results:
        mark = "[PASS]" if ok else "[FAIL]"
        print(f"  {mark:<8} {mod:<28} -> sch_{mod}.bdf + {mod}.bsf + {mod}.v")
        if not ok: all_ok = False

    print("=" * 80)
    print(f"Overall Result: {'100% ALL BDF REWRITTEN AND VERIFIED!' if all_ok else 'SOME MODULES FAILED'}")
    return 0 if all_ok else 1

if __name__ == "__main__":
    sys.exit(main())
